            "- **MUJI式极简日用品文案**：\n  > 不是“这个最好”，而是“这样就好”。  \n  > 剔除一切多余的包装与繁复的染色，保留棉麻原生的素白与微糙。  \n  > 穿在身上，不张扬，也不局促。让物回归物本身，让生活重获呼吸的自由。",
